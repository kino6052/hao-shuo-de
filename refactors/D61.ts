//     zhēn-shí, xiàn-shí), xīn 新 (xīn-nián), hái 孩 (hái-zi), and 名 now
//     also in míng-zi.
//   - gùnzi leaves: a stick is cháng-de dōng-xi.
//   - Sentences: chī dōng-xi -> chī fàn, shénme rén -> shéi, hair
//     (tóu-shàng-de máo) -> tóu-fā. jiàzhí, máo, dēng, tōng and qíguài stay.
//   - The compound rule then puts each Mandarin word the new roots can write
//     first in the composite dictionary (proposed).
