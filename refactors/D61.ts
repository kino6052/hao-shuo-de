// load off generic heads like dōng-xi, zuò and rén).
//   - 22 new words: ràng (let, make), yǐ, hái, xiē, zhǐ, shéi, tóng, ér, zi,
//     shū, zì, xiǎng, zǒu, fàn, wǎn, zuó, bǎi, zhòng, jiàn, tí, huà, cháng.
