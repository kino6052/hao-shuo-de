#!/usr/bin/env node
// The round trip on the book (BROWSER_TRANSLATOR_PLAN.md B3): every Hao-shuo-de sentence of the book -> its first
// reading as a meaning tree -> the sentence built from the tree -> parsed again (src/lib/grammar/round-trip.js).
// Prints the counts and writes kb/reports/round-trip.md: each sentence that fails, why, and the patterns it uses,
// then the spelling differences (counted, not failures).
//
//   node scripts/round-trip.js                 every sentence (lessons, composite examples, stories, phrase book)
//   node scripts/round-trip.js --kind story    one kind (lesson_example, composite_example, story, phrase_book, ...)
//   node scripts/round-trip.js --limit 200     the first 200 sentences only
//   node scripts/round-trip.js --stdout        print the report instead of writing it
//
// Exit 1 when a sentence that parses fails the round trip.

import { writeFileSync, mkdirSync } from 'fs';
import { resolve } from 'path';
import { fileURLToPath } from 'url';
import { openKb } from './kb.js';
import { makeTrees, spellingHabits } from '../src/lib/grammar/tree.js';
import { roundTrip, summarize } from '../src/lib/grammar/round-trip.js';
import { patternsOf } from '../src/lib/grammar/parser.js';
import { pinyinProblems } from '../src/lib/pinyin-refs.js';
import { splitSentences } from '../src/lib/kb/parse.js';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const OUT = resolve(ROOT, 'kb/reports/round-trip.md');
const args = process.argv.slice(2);
const option = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const kind = option('--kind');
const limit = Number(option('--limit') ?? Infinity);
const stdout = args.includes('--stdout');

const started = Date.now();
const kb = await openKb();
const parser = kb.parse.parser;
const words = kb.parse.words;
// every sentence once, as word refs, with the kind of text it comes from
const seen = new Map();
for (const s of kb.facts.sentences) {
  if (kind && s.kind !== kind) continue;
  let refs = String(s.pinyin ?? '');
  if (!refs.includes('{{')) {
    const converted = pinyinProblems(refs, words, { composites: kb.source.composites });
    if (converted.problems.length) continue;
    refs = converted.refs;
  }
  for (const text of splitSentences(refs)) if (!seen.has(text)) seen.set(text, s.kind);
}
const todo = [...seen].slice(0, limit);
// the build spells the way the book does, learned from all of its sentences (not only the ones tried)
const habits = spellingHabits(seen.keys());
const trees = makeTrees({ rules: parser.rules, glue: parser.grammar.glue, words, composites: kb.source.composites, habits });

const results = [];
todo.forEach(([text, from], i) => {
  results.push({ ...roundTrip(text, { parser, trees }), from });
  if (!stdout && (i + 1) % 500 === 0) process.stderr.write(`  ${i + 1} of ${todo.length}\n`);
});

const sum = summarize(results);
const parsed = results.filter((r) => r.parsed);
const failed = parsed.filter((r) => !r.ok);

// a spelling difference, named by the first normalization that removes it
const spellings = new Map();
const norms = [
  ['capitals', (s) => s.replace(/\{\{(Word|Light):/g, (m, k) => `{{${k.toLowerCase()}:`)],
  ['hyphens', (s) => s.replace(/\}\}-/g, '}} ').replace(/-"/g, ' "').replace(/"-/g, '" ')],
  ['a bare ge for a light one', (s) => s.replace(/(^|[ -])ge\b/g, '$1{{light:ge4}}')],
  ['light syllables', (s) => s.replace(/\{\{light:/g, '{{word:')],
  ['the end mark', (s) => s.replace(/[.!?…]+$/, '')],
];
for (const r of parsed.filter((r) => r.sameWords && !r.sameSpelling)) {
  let a = r.text.trim();
  let b = r.built;
  let why = 'other';
  for (const [name, f] of norms) {
    a = f(a);
    b = f(b);
    if (a === b) {
      why = name;
      break;
    }
  }
  if (!spellings.has(why)) spellings.set(why, []);
  spellings.get(why).push(r);
}

const pct = (n, of) => `${n} (${of ? Math.round((100 * n) / of) : 0}%)`;
const lines = [
  '# The round trip on the book',
  '',
  `Generated by \`node scripts/round-trip.js\` (BROWSER_TRANSLATOR_PLAN.md B3)${kind ? `, kind ${kind}` : ''}. Each sentence's first reading becomes a meaning tree (src/lib/grammar/tree.js), the tree builds a sentence, and the sentence is parsed again.`,
  '',
  `- Sentences: ${sum.sentences}; parse: ${pct(sum.parsed, sum.sentences)}`,
  `- Of those that parse: the round trip holds for ${pct(sum.ok, sum.parsed)}`,
  `  - the tree passes its checks: ${pct(sum.parsed - sum.problems, sum.parsed)}`,
  `  - the same words in the same order: ${pct(sum.sameWords, sum.parsed)}`,
  `  - the tree is the built sentence's first reading: ${pct(sum.first, sum.parsed)}; a later one: ${pct(sum.later, sum.parsed)}; none of the first 200: ${pct(sum.lost, sum.parsed)}`,
  `  - spelled exactly the same: ${pct(sum.sameSpelling, sum.parsed)}`,
  '',
  '## Failures',
  '',
  ...(failed.length ? [] : ['None.']),
  ...failed.map((r) => {
    const why = [...r.problems, ...(r.sameWords ? [] : ['the built sentence has other words']), ...(r.at < 0 ? ['the tree does not come back'] : [])];
    return `- ${r.text}  \n  built: ${r.built}  \n  ${why.join('; ')} (${r.from}; patterns: ${patternsOfTree(r.tree).join(', ')})`;
  }),
  '',
  '## Spelling differences (not failures)',
  '',
  ...[...spellings].sort((a, b) => b[1].length - a[1].length).flatMap(([why, list]) => [
    `- ${why}: ${list.length}`,
    ...list.slice(0, 5).map((r) => `  - ${r.text}  \n    built: ${r.built}`),
  ]),
  '',
  '## Readings',
  '',
  `The built sentences have ${parsed.length ? (parsed.reduce((n, r) => n + (r.readings ?? 0), 0) / parsed.length).toFixed(1) : 0} readings on average; the tree is a later reading than the first for ${sum.later}.`,
  '',
  `### The first reading takes a composite word by word: ${sum.split} sentences`,
  '',
  'The book joins the words (dòng-wù), they spell a composite, and the first reading still reads them one by one. The round trip holds (the tree is that reading), but the reading is probably not the one meant: a question about the reading order, for the author.',
  '',
  ...splitList(),
  '',
];

function splitList() {
  const byZh = new Map();
  for (const r of parsed) for (const s of r.split ?? []) byZh.set(s.zh, [...(byZh.get(s.zh) ?? []), r]);
  return [...byZh]
    .sort((a, b) => b[1].length - a[1].length)
    .map(([zh, list]) => `- ${zh} (${list[0].split.find((s) => s.zh === zh).words.join(' ')}): ${list.length}, e.g. ${list[0].text}`);
}

function patternsOfTree(tree) {
  const rules = [];
  const walk = (t) => {
    if (!t?.rule) return;
    rules.push({ pattern: t.rule.split('#')[0] });
    Object.values(t.slots ?? {}).forEach(walk);
  };
  walk(tree);
  return patternsOf({ children: rules });
}

const report = lines.join('\n');
if (stdout) console.log(report);
else {
  mkdirSync(resolve(ROOT, 'kb/reports'), { recursive: true });
  writeFileSync(OUT, report);
  console.log(`round trip: ${sum.ok} of ${sum.parsed} parsed sentences hold (${sum.sentences} sentences, ${sum.sentences - sum.parsed} don't parse); ${sum.sameSpelling} spelled the same; ${((Date.now() - started) / 1000).toFixed(1)} s -> kb/reports/round-trip.md`);
}
process.exit(failed.length ? 1 : 0);
