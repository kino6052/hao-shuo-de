const TODO = { eng: 'TODO', rus: 'TODO', zh: 'TODO' };

// -> a new word's data from an op's partial data (TODO where not given).
function newWordData(id, partial = {}) {
  return {
    term: partial.term ?? idToTerm(id),
    hanzi: partial.hanzi,
    pos: partial.pos ?? TODO,
    definition: partial.definition ?? TODO,
    necessity: partial.necessity ?? { index: 1, eng: 'TODO', rus: 'TODO' },
    ...(partial.senses ? { senses: partial.senses } : {}),
  };
}

// -> the hanzi a word has inside a given compound (its sense's, if listed).
function hanziIn(ws, id, compound) {
  const w = ws.word(id);
  for (const s of Object.values(w.senses ?? {})) if (s.compounds.includes(compound)) return s.hanzi;
  return w.hanzi;
}

const OPS = {
  // { op: "add", id, hanzi, term?, pos?, definition?, necessity?, senses?, category }
  add(ws, op) {
    if (ws.hasWord(op.id)) throw new Error(`${op.id} already exists`);
    if (!op.hanzi) throw new Error(`add ${op.id}: give its hanzi`);
    ws.setWord(op.id, newWordData(op.id, op));
    if (op.category) placeInCategory(ws, op.id, op.category);
    else ws.note('todo', `${op.id}: put it in a category (maps/categories.ts) -- check-data fails until then`);
    if (!op.definition || !op.pos || !op.necessity) ws.note('todo', `${op.id}: fill in its definition, part of speech and necessity (TODO in ${ws.wordPath(op.id)})`);
  },

  // { op: "edit", id, set: { term?, hanzi?, pos?, definition?, necessity?, senses? } }
  edit(ws, op) {
    const w = ws.word(op.id);
    ws.setWord(op.id, { ...w, ...op.set });
  },

  // { op: "sense", id, key, hanzi, eng, rus, why: { eng, rus }, compounds: ["shi2 jian1", ...] }
  sense(ws, op) {
    const w = ws.word(op.id);
    const { op: _op, id: _id, key, ...sense } = op;
    ws.setWord(op.id, { ...w, senses: { ...(w.senses ?? {}), [key]: sense } });
  },

  // { op: "senseCompounds", id, key, add: ["shi4 shi2", ...] } -- more compounds for a sense
  senseCompounds(ws, op) {
    const w = ws.word(op.id);
    const s = w.senses?.[op.key];
    if (!s) throw new Error(`${op.id} has no sense "${op.key}"`);
    s.compounds = [...new Set([...s.compounds, ...op.add])];
    ws.setWord(op.id, w);
  },

  // { op: "category", id, to: "<leaf key>" }
  category(ws, op) {
    editCategories(ws, (ids) => ids.filter((x) => x !== op.id));
    placeInCategory(ws, op.id, op.to);
  },

  // { op: "split", id, into: [ids], light?: [ids], senses?: { id: senseKey }, words?: { id: partial data }, cards?: { id: { en, ru } } }
  // Every ref to id becomes the parts joined by hyphens; the parts' hanzi
  // (a listed sense's, inside the new compound) must equal id's hanzi.
  split(ws, op) {
    const { id, into } = op;
    const old = ws.word(id);
    const light = new Set(op.light ?? []);
    const compound = into.join(' ');
    for (const p of into) {
      if (ws.hasWord(p)) continue;
      const partial = op.words?.[p] ?? {};
      if (!partial.hanzi) {
        // the old hanzi, one character per syllable, cut at the parts' syllables
        const chars = [...old.hanzi];
        const counts = into.map((x) => idSyllables(x).length);
        if (counts.reduce((a, b) => a + b, 0) !== chars.length) throw new Error(`split ${id}: give the hanzi of new part ${p} (words.${p}.hanzi)`);
        const at = counts.slice(0, into.indexOf(p)).reduce((a, b) => a + b, 0);
        partial.hanzi = chars.slice(at, at + counts[into.indexOf(p)]).join('');
      }
      ws.setWord(p, newWordData(p, partial));
      if (!partial.definition || !partial.necessity || !partial.pos) ws.note('todo', `${p}: new word from splitting ${id} -- fill in its definition, part of speech and necessity`);
    }
    const joined = into.map((p) => hanziIn(ws, p, compound)).join('');
    if (joined !== old.hanzi) throw new Error(`split ${id}: the parts write ${joined}, but ${id} is ${old.hanzi} -- list the compound "${compound}" under the right sense first, or use replace`);
    // refs
    rewriteAll(ws, id, (kind) => into.map((p, i) => ref(i === 0 ? kind : kind === 'light' || kind === 'Light' ? 'light' : 'word', p, light.has(p))).join('-'));
    // cards: the parts take the old card's place; a part taught later moves here
    const all = cards(ws);
    const mine = all.filter((c) => c.word === id);
    if (mine.length) {
      const at = mine[0];
      const list = [];
      const moved = [];
      for (const p of into) {
        const sense = op.senses?.[p];
        const existing = all.find((c) => c.word === p && c.sense === sense);
        if (existing && existing.order < at.order) continue;
        if (existing) {
          const src = ws.get(existing.file);
          list.push(cardData(src, existing.obj));
          moved.push(existing);
          ws.note('card', `${cardKey(p, sense)}: card moved from ${existing.lesson}/${existing.module} to ${at.lesson}/${at.module} (taught earlier now)`);
        } else {
          const c = op.cards?.[p] ? { word: p, ...(sense ? { sense } : {}), ...op.cards[p] } : newCard(ws, p, sense);
          list.push(c);
          if (!op.cards?.[p]) ws.note('card', `${cardKey(p, sense)}: new card in ${at.lesson}/${at.module}, gloss "${c.en}" / "${c.ru}" taken from the definition -- check it`);
        }
      }
      // remove moved cards first (later in the book, so the slot's position holds
      // unless they share its file -- re-find the slot after each removal)
      for (const m of moved.sort((a, b) => b.order - a.order)) {
        const fresh = cards(ws).find((c) => c.file === m.file && c.word === m.word && c.sense === m.sense);
        removeCard(ws, fresh);
      }
      const slot = cards(ws).find((c) => c.word === id);
      spliceCards(ws, slot, list);
      for (const extra of cards(ws).filter((c) => c.word === id)) removeCard(ws, extra);
    }
    // maps and coverage
    const leaf = categoryOf(ws, id);
    const placed = new Set();
    walkCategories(ws.data(`${MAPS}categories.ts`), (c) => (c.wordIds ?? []).forEach((w) => placed.add(w)));
    editCategories(ws, (ids) => ids.flatMap((x) => (x === id ? into.filter((p) => !placed.has(p)) : [x])));
    if (!leaf) ws.note('todo', `${id} had no category; place its new parts`);
    editRelations(ws, (p) => (p.includes(id) ? null : p), (w, forms) => (w === id ? null : [w, forms]), `${id} was split`);
    editCoverageWords(ws, (words) => (words.includes(id) ? words.flatMap((w) => (w === id ? into : [w])) : words));
    // the composite that was the word itself
    for (const { path, entry } of ws.composites()) {
      if (entry.zh === old.hanzi && entry.fit === 'word') ws.note('composite', `${path}: ${entry.zh} was the word ${id}; now ${into.join('-')} -- its fit "word" may now be "natural"`);
    }
    // plain pinyin of the old word becomes the parts' pinyin (dòngwù -> dòng-wù)
    const newTerm = into.map((p) => (light.has(p) ? toneless(ws.word(p).term) : ws.word(p).term)).join('-');
    rewriteMentions(ws, id, old.term, newTerm);
    noteMentions(ws, id, old.term, `${id} was split`);
    ws.remove(ws.wordPath(id));
  },

  // { op: "replace", id, with: "<form of refs>", hanzi?: { "部分": "分" }, keep?: true, words?: [ids] }
  // Every ref to id becomes the form; each changed sentence is noted for review.
  // keep: the id stays (it is reused with a new meaning by a later edit op).
  replace(ws, op) {
    const { id, with: form } = op;
    const old = ws.word(id);
    for (const m of form.matchAll(wordRefRe())) if (!ws.hasWord(m[2])) throw new Error(`replace ${id}: the form names ${m[2]}, which isn't a word (add it first)`);
    const map = Object.entries(op.hanzi ?? {});
    const hanziFn = map.length ? (h) => map.reduce((s, [a, b]) => s.split(a).join(b), h) : undefined;
    rewriteAll(ws, id, (kind) => (kind === 'Word' || kind === 'Light' ? capitalizeForm(form) : form), { hanziFn, noteSentences: true, label: `${id} -> ${form}` });
    const formIds = [...form.matchAll(wordRefRe())].map((m) => m[2]);
    const single = formIds.length === 1 && form === `{{word:${formIds[0]}}}` ? formIds[0] : null;
    editCoverageWords(ws, (words) => (words.includes(id) ? words.flatMap((w) => (w === id ? (op.words ?? formIds) : [w])) : words));
    if (!op.keep) {
      editRelations(
        ws,
        (p) => (p.includes(id) ? (single && !p.includes(single) ? p.map((x) => (x === id ? single : x)) : null) : p),
        (w, forms) => (w === id ? (single ? [single, forms] : null) : [w, forms]),
        `${id} was replaced`,
      );
      for (const c of cards(ws).filter((c) => c.word === id)) ws.note('card', `${c.lesson}/${c.module}: removed the card for ${id}; teach ${form} there if it's new`);
      let c;
      while ((c = cards(ws).find((x) => x.word === id))) removeCard(ws, c);
      editCategories(ws, (ids) => ids.filter((x) => x !== id));
      if (single) rewriteMentions(ws, id, old.term, ws.word(single).term);
      noteMentions(ws, id, old.term, `${id} was replaced`);
      ws.remove(ws.wordPath(id));
    } else {
      ws.note('todo', `${id} is kept for reuse: change its file and card with edit/move ops`);
    }
  },

  // { op: "refs", pattern, to, hanzi?: [pattern, to], label? } -- a regex over the
  // text (refs included, e.g. "\\{\\{(w|W)ord:zuo4\\}\\} \\{\\{word:zai4\\}\\}"); each
  // changed sentence's hanzi gets the hanzi regex, and is noted for review.
  refs(ws, op) {
    const re = new RegExp(op.pattern, 'g');
    const hz = op.hanzi ? [new RegExp(op.hanzi[0], 'g'), op.hanzi[1]] : null;
    rewriteText(ws, (t) => t.replace(re, op.to), {
      hanziFn: hz ? (h) => h.replace(hz[0], hz[1]) : undefined,
      noteSentences: true,
      label: op.label ?? op.pattern,
      has: (t) => new RegExp(op.pattern).test(t),
    });
  },

  // { op: "rename", id, to } -- a new id (and its refs, cards, maps, coverage, senses)
  rename(ws, op) {
    const { id, to } = op;
    if (ws.hasWord(to)) throw new Error(`rename ${id}: ${to} already exists`);
    const w = ws.word(id);
    rewriteAll(ws, id, (kind) => `{{${kind}:${to}}}`);
    for (const path of ws.files(LESSONS_DIR)) {
      const src = ws.get(path);
      const r = rewriteStrings(src, (v, s) => (s.key === 'word' && v === id && s.obj?.key === 'words' ? to : v));
      if (r.text !== src) ws.set(path, r.text);
    }
    editCategories(ws, (ids) => ids.map((x) => (x === id ? to : x)));
    editRelations(ws, (p) => p.map((x) => (x === id ? to : x)), (k, f) => [k === id ? to : k, f], 'rename');
    editCoverageWords(ws, (words) => (words.includes(id) ? words.map((x) => (x === id ? to : x)) : words));
    for (const other of ws.wordIds()) {
      const o = ws.word(other);
      if (!o.senses) continue;
      let touched = false;
      for (const s of Object.values(o.senses)) {
        const nc = s.compounds.map((c) => c.split(' ').map((p) => (p === id ? to : p)).join(' '));
        if (nc.join() !== s.compounds.join()) (s.compounds = nc), (touched = true);
      }
      if (touched) ws.setWord(other, o);
    }
    ws.remove(ws.wordPath(id));
    ws.setWord(to, w);
    if (w.senses) {
      for (const s of Object.values(w.senses)) s.compounds = s.compounds.map((c) => c.split(' ').map((p) => (p === id ? to : p)).join(' '));
      ws.setWord(to, w);
    }
    noteMentions(ws, id, '', 'renamed');
  },

  // { op: "remove", id } -- refuses while the word is used
  remove(ws, op) {
    const { id } = op;
    const uses = ws.files().filter((p) => p !== ws.wordPath(id) && ws.get(p).includes(`:${id}}}`));
    if (uses.length) throw new Error(`remove ${id}: still used in ${uses.length} file(s): ${uses.slice(0, 5).join(', ')}${uses.length > 5 ? ', ...' : ''}`);
    const w = ws.word(id);
    let c;
    while ((c = cards(ws).find((x) => x.word === id))) removeCard(ws, c);
    editCategories(ws, (ids) => ids.filter((x) => x !== id));
    editRelations(ws, (p) => (p.includes(id) ? null : p), (k, f) => (k === id ? null : [k, f]), `${id} was removed`);
    editCoverageWords(ws, (words) => (words.includes(id) ? words.filter((x) => x !== id) : words));
    noteMentions(ws, id, w.term, `${id} was removed`);
    ws.remove(ws.wordPath(id));
  },

  // { op: "card", id, sense?, to: "lesson/module", en, ru, hanzi? } -- add a card
  card(ws, op) {
    const file = moduleFile(ws, op.to);
    const c = { word: op.id, ...(op.sense ? { sense: op.sense } : {}), ...(op.hanzi ? { hanzi: op.hanzi } : {}), en: op.en, ru: op.ru };
    appendCard(ws, file, op.en ? c : newCard(ws, op.id, op.sense));
  },

  // { op: "uncard", id, sense? } -- remove the word's (sense's) card
  uncard(ws, op) {
    const c = cards(ws).find((x) => x.word === op.id && x.sense === op.sense);
    if (!c) throw new Error(`uncard: no card for ${cardKey(op.id, op.sense)}`);
    removeCard(ws, c);
  },

  // { op: "move", id, sense?, to: "lesson/module" } -- move the card
  move(ws, op) {
    const c = cards(ws).find((x) => x.word === op.id && x.sense === op.sense);
    if (!c) throw new Error(`move: no card for ${cardKey(op.id, op.sense)}`);
    const data = cardData(ws.get(c.file), c.obj);
    removeCard(ws, c);
    appendCard(ws, moduleFile(ws, op.to), data);
  },

  // { op: "relation", kind: "antonyms" | "synonyms", add?: [a, b], remove?: [a, b] }
  relation(ws, op) {
    const path = `${MAPS}${op.kind}.ts`;
    const r = ws.data(path);
    if (op.remove) r.pairs = r.pairs.filter((p) => !(p.includes(op.remove[0]) && p.includes(op.remove[1])));
    if (op.add) r.pairs.push(op.add);
    ws.setData(path, r);
  },

  // { op: "composite", zh, set?: { fit, role, transparent, ... }, addForm?: [form, hanzi], create?: { rank, phase, py, en, ru } }
  composite(ws, op) {
    let found = ws.composites().find(({ entry }) => entry.zh === op.zh);
    if (!found) {
      if (!op.create) throw new Error(`composite: no entry ${op.zh} (give create: { rank, phase, py, en, ru } to add one)`);
      found = { path: null, entry: { ...op.create, zh: op.zh, proposed: true } };
    }
    const e = { ...found.entry, ...(op.set ?? {}) };
    if (op.addForm) {
      const [form, hanzi] = op.addForm;
      if (!(e.hsd ?? []).includes(form)) {
        e.hsd = [...(e.hsd ?? []), form];
        e.tts = [...(e.tts ?? []), hanzi];
      }
    }
    if (found.path) ws.setComposite(found.path, e);
    else ws.set(`${COMPOSITES_DIR}${compositeFileName(e)}`, `import { composite } from "../../lib/composite.ts";\n\nexport default composite(${tsLiteral(e)});\n`);
  },

  // { op: "compounds" } -- the compound rule over every composite: a Chinese
  // word now made of Hao-shuo-de words gets that compound as its first form
  // (marked proposed), and its old forms follow after " / " as constructive ones.
  compounds(ws) {
    const words = Object.fromEntries(ws.wordIds().map((id) => [id, ws.word(id)]));
    const split = compoundSplitter(words);
    for (const { path, entry } of ws.composites()) {
      if (entry.fit === 'name' || entry.fit === 'skip') continue;
      const ids = split(entry.zh, entry.py);
      if (!ids) continue;
      const forms = entry.hsd ?? [];
      if ((entry.tts ?? []).includes(entry.zh) || forms.some((f) => wordRefIds(f).join(' ') === ids.join(' '))) continue;
      const form = compoundForm(ids);
      const e = { ...entry, hsd: [form, ...forms], tts: [entry.zh, ...(entry.tts ?? [])], fit: ids.length === 1 ? 'word' : 'natural', proposed: true };
      ws.setComposite(path, e);
      ws.note('composite', `${entry.zh} ${entry.en}: ${ids.map((id) => words[id].term).join('-')} first${forms.length ? ` (then ${forms.length} older form(s))` : ''}`);
    }
  },

  // { op: "text", file, from, to, all? } -- a hand edit kept in the list
  text(ws, op) {
    const src = ws.get(op.file);
    if (!src.includes(op.from)) throw new Error(`text: "${op.from.slice(0, 60)}" not found in ${op.file}`);
    ws.set(op.file, op.all ? src.split(op.from).join(op.to) : src.replace(op.from, op.to));
  },
};

function placeInCategory(ws, id, leafKey) {
  let found = false;
  editCategories(ws, (ids, c) => {
    if (c.key !== leafKey) return ids;
    found = true;
    return ids.includes(id) ? ids : [...ids, id];
  });
  if (!found) throw new Error(`no category leaf "${leafKey}"`);
}

export const OP_NAMES = Object.keys(OPS);

// Applies ops in order; an op that throws stops the run with its index.
export function applyOps(ws, ops) {
  ops.forEach((op, i) => {
    const fn = OPS[op.op];
    if (!fn) throw new Error(`op ${i + 1}: unknown op "${op.op}" (one of ${OP_NAMES.join(', ')})`);
    try {
      fn(ws, op);
    } catch (e) {
      e.message = `op ${i + 1} (${op.op} ${op.id ?? op.file ?? ''}): ${e.message}`;
      throw e;
    }
  });
}

