// -- the workspace -------------------------------------------------------------

const TEXT_EXT = new Set(['.ts', '.js', '.jsx', '.yaml', '.md']);
const SKIP = new Set([
  'src/data/words/index.ts',
  'src/data/composites/index.ts',
  'src/data/coverage/index.ts',
  // generated by scripts/generate-dictionary.js
  'src/content/dictionary.md',
  'src/content/dictionary.rus.md',
  'src/content/dictionary.zh.md',
]);

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    const p = resolve(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (TEXT_EXT.has(extname(name))) out.push(p);
  }
  return out;
}

const rel = (p) => relative(ROOT, p).replace(/\\/g, '/');
const WORDS_DIR = 'src/data/words/';
const COMPOSITES_DIR = 'src/data/composites/';
const LESSONS_DIR = 'src/content/lessons/';

// A data file: "<prefix><literal>);\n" -- the prefix holds the comments, the
// import and "export default helper(" (plus "id", for a word).
function splitData(text, path) {
  const m = text.match(/^([\s\S]*?export default \w+\((?:"[^"]+", )?)([\s\S]*)\);\n$/);
  if (!m) throw new Error(`${path}: not a data file`);
  return { prefix: m[1], value: Function(`return (${m[2]});`)() };
}

const LF = String.fromCharCode(10);
const CRLF = String.fromCharCode(13, 10);

export class Workspace {
  constructor() {
    this.orig = new Map();
    this.text = new Map();
    // files are edited with LF line ends and written back with the ones they had
    this.crlf = new Set();
    const files = [...walk(resolve(ROOT, 'src'), []), ...walk(resolve(ROOT, 'scripts'), []).filter((p) => p.endsWith('.test.js'))];
    for (const p of files) {
      const r = rel(p);
      if (SKIP.has(r)) continue;
      let t = readFileSync(p, 'utf-8');
      if (t.includes(CRLF)) {
        this.crlf.add(r);
        t = t.split(CRLF).join(LF);
      }
      this.orig.set(r, t);
      this.text.set(r, t);
    }
    this.notes = [];
  }

  note(kind, text) {
    this.notes.push({ kind, text });
  }

  has(r) {
    return this.text.get(r) != null;
  }
  get(r) {
    const t = this.text.get(r);
    if (t == null) throw new Error(`no file ${r}`);
    return t;
  }
  set(r, t) {
    this.text.set(r, t);
  }
  remove(r) {
    this.text.set(r, null);
  }
  files(prefix = '') {
    return [...this.text.keys()].filter((r) => r.startsWith(prefix) && this.text.get(r) != null);
  }

  // -- data files --
  data(r) {
    return splitData(this.get(r), r).value;
  }
  setData(r, value) {
    const { prefix } = splitData(this.get(r), r);
    this.set(r, `${prefix}${tsLiteral(value)});\n`);
  }

  wordPath(id) {
    return `${WORDS_DIR}${id}.ts`;
  }
  wordIds() {
    return this.files(WORDS_DIR).map((r) => r.slice(WORDS_DIR.length, -3));
  }
  hasWord(id) {
    return this.has(this.wordPath(id));
  }
  word(id) {
    if (!this.hasWord(id)) throw new Error(`no word ${id}`);
    return this.data(this.wordPath(id));
  }
  setWord(id, value) {
    const order = ['term', 'hanzi', 'pos', 'definition', 'necessity', 'maps', 'senses'];
    const out = {};
    for (const k of [...order, ...Object.keys(value).filter((k) => !order.includes(k))]) if (value[k] !== undefined) out[k] = value[k];
    this.set(this.wordPath(id), `import { word } from "../../lib/word.ts";\n\nexport default word(${JSON.stringify(id)}, ${tsLiteral(out)});\n`);
  }

  composites() {
    return this.files(COMPOSITES_DIR).filter((r) => !r.endsWith('/meta.ts')).map((r) => ({ path: r, entry: this.data(r) }));
  }
  setComposite(path, entry) {
    const want = COMPOSITES_DIR + compositeFileName(entry);
    if (want !== path) this.remove(path);
    const text = `import { composite } from "../../lib/composite.ts";\n\nexport default composite(${tsLiteral(entry)});\n`;
    this.set(want, text);
  }

  // -> [{ path, before, after }] for every file that changed.
  changes() {
    const out = [];
    for (const [r, after] of this.text) {
      const before = this.orig.get(r) ?? null;
      if (before !== after) out.push({ path: r, before, after });
    }
    return out.sort((a, b) => (a.path < b.path ? -1 : 1));
  }

  write() {
    for (const { path, after } of this.changes()) {
      const p = resolve(ROOT, path);
      if (after == null) {
        if (existsSync(p)) unlinkSync(p);
      } else {
        mkdirSync(dirname(p), { recursive: true });
        writeFileSync(p, this.crlf.has(path) ? after.split(LF).join(CRLF) : after);
      }
    }
  }
}

// -- string literals in JS/TS -----------------------------------------------------

// -> { strings, objects } for a JS/TS source: every string literal with its
// span, the key it's the value of (or the key of the array it's in), and the
// innermost object it sits in; every object literal with its span and the
// key it's the value of. Comments are skipped. Good enough for the content
// files, which are plain data.
export function scanSource(src) {
  const strings = [];
  const objects = [];
  const stack = []; // { type: '{' | '[', key, obj, lastKey }
  let i = 0;
  const top = () => stack[stack.length - 1];
  const innerObj = () => {
    for (let k = stack.length - 1; k >= 0; k--) if (stack[k].type === '{') return stack[k];
    return null;
  };
  const valueKey = () => {
    const t = top();
    if (!t) return null;
    return t.type === '{' ? t.lastKey : t.key;
  };
  while (i < src.length) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
      continue;
    }
    if (c === '/' && src[i + 1] === '*') {
      i = src.indexOf('*/', i + 2) + 2;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') {
      let j = i + 1;
      while (j < src.length && src[j] !== c) j += src[j] === '\\' ? 2 : 1;
      const start = i;
      const end = j + 1;
      // A string followed by ':' is a key ("lóng": ...), not a value.
      const after = src.slice(end).match(/^\s*:/);
      const t = top();
      if (after && t?.type === '{') t.lastKey = src.slice(start + 1, end - 1);
      else strings.push({ start, end, key: valueKey(), obj: innerObj()?.obj ?? null });
      i = end;
      continue;
    }
    if (c === '{' || c === '[') {
      const key = valueKey();
      const frame = { type: c, key, lastKey: null, obj: null };
      if (c === '{') {
        frame.obj = { id: objects.length, start: i, end: -1, key, parent: innerObj()?.obj ?? null };
        objects.push(frame.obj);
      }
      stack.push(frame);
      i++;
      continue;
    }
    if (c === '}' || c === ']') {
      const f = stack.pop();
      if (f?.obj) f.obj.end = i + 1;
      i++;
      continue;
    }
    if (c === ',') {
      const t = top();
      if (t?.type === '{') t.lastKey = null;
      i++;
      continue;
    }
    if (/[A-Za-z_$]/.test(c)) {
      let j = i;
      while (j < src.length && /[\w$]/.test(src[j])) j++;
      const ident = src.slice(i, j);
      const t = top();
      if (t?.type === '{' && /^\s*:/.test(src.slice(j))) t.lastKey = ident;
      i = j;
      continue;
    }
    i++;
  }
  return { strings, objects };
}

// -> a string literal's value (the content files only use JSON-style escapes).
export function literalValue(src, s) {
  const raw = src.slice(s.start, s.end);
  if (raw[0] === '"') return JSON.parse(raw);
  return raw.slice(1, -1).replace(/\\(.)/g, '$1');
}

// -> literal text for a value, quoted the way the original was.
function literalText(value, quote) {
  if (quote === '"') return JSON.stringify(value);
  return quote + value.replace(/\\/g, '\\\\').replace(new RegExp(quote, 'g'), `\\${quote}`) + quote;
}

const SENTENCE_KEYS = new Set(['pinyin', 'answer']);
const HANZI_KEYS = new Set(['hanzi', 'ttsText']);

// Rewrites a JS/TS source's string literals with fn(value, s) -> value. When a
// sentence (`pinyin`/`answer`) changes, hanziFn(hanzi) -> hanzi rewrites the
// `hanzi`/`ttsText` of the same object. -> { text, changed: [{ obj, key, before, after, hanzi? }] }
export function rewriteStrings(src, fn, hanziFn) {
  const { strings } = scanSource(src);
  const edits = [];
  const changed = [];
  const sentenceObjs = new Set();
  for (const s of strings) {
    const v = literalValue(src, s);
    const nv = fn(v, s);
    if (nv === v) continue;
    edits.push({ s, value: nv });
    changed.push({ obj: s.obj?.id ?? null, key: s.key, before: v, after: nv });
    if (SENTENCE_KEYS.has(s.key) && s.obj) sentenceObjs.add(s.obj.id);
  }
  if (hanziFn) {
    for (const s of strings) {
      if (!HANZI_KEYS.has(s.key) || !s.obj || !sentenceObjs.has(s.obj.id)) continue;
      const v = literalValue(src, s);
      const nv = hanziFn(v);
      const c = changed.find((x) => x.obj === s.obj.id && SENTENCE_KEYS.has(x.key));
      if (c) c.hanzi = { before: v, after: nv };
      if (nv !== v) edits.push({ s, value: nv });
    }
  }
  edits.sort((a, b) => b.s.start - a.s.start);
  let out = src;
  for (const { s, value } of edits) out = out.slice(0, s.start) + literalText(value, src[s.start]) + out.slice(s.end);
  return { text: out, changed };
}

// -> text with each ref to `id` replaced by make(kind) (kind: word, Word, light, Light).
export function replaceRefsTo(text, id, make) {
  return text.replace(wordRefRe(), (full, kind, ref) => (ref === id ? make(kind) : full));
}

// -> a ref of a kind, with the case of `kind` kept and its lightness given.
const ref = (kind, id, light = false) => {
  const cap = kind === 'Word' || kind === 'Light';
  const k = light || kind === 'light' || kind === 'Light' ? 'light' : 'word';
  return `{{${cap ? k[0].toUpperCase() + k.slice(1) : k}:${id}}}`;
};

// -> the form with its first ref capitalized (for a sentence-initial use).
function capitalizeForm(form) {
  if (/^\{\{(word|light):/.test(form)) return form.replace(/^\{\{(\w)/, (_, c) => `{{${c.toUpperCase()}`);
  return form.charAt(0).toUpperCase() + form.slice(1);
}

// -- lesson cards --------------------------------------------------------------

// -> the module files of a lesson, in reading order (from its index.ts).
function moduleFiles(ws, lesson) {
  const index = ws.get(`${LESSONS_DIR}${lesson}/index.ts`);
  const imports = new Map([...index.matchAll(/^import (\w+) from "\.\/([\w-]+\.ts)";/gm)].map((m) => [m[1], m[2]]));
  const list = index.match(/modules:\s*\[([^\]]*)\]/)?.[1] ?? '';
  return list.split(',').map((s) => s.trim()).filter(Boolean).map((name) => `${LESSONS_DIR}${lesson}/${imports.get(name)}`);
}

// -> every card in the book, in reading order:
// [{ word, sense, file, lesson, module, order, obj, src }]
export function cards(ws) {
  const out = [];
  LESSON_IDS.forEach((lesson) => {
    if (!ws.has(`${LESSONS_DIR}${lesson}/index.ts`)) return;
    for (const file of moduleFiles(ws, lesson)) {
      if (!ws.has(file)) continue;
      const src = ws.get(file);
      const { strings, objects } = scanSource(src);
      const module = src.match(/lessonModule\(\{\s*id:\s*"([^"]+)"/)?.[1];
      for (const o of objects) {
        if (o.key !== 'words') continue;
        const own = strings.filter((s) => s.obj?.id === o.id);
        const w = own.find((s) => s.key === 'word');
        if (!w) continue;
        const sense = own.find((s) => s.key === 'sense');
        out.push({
          word: literalValue(src, w),
          sense: sense ? literalValue(src, sense) : undefined,
          file,
          lesson,
          module,
          order: out.length,
          obj: o,
        });
      }
    }
  });
  return out;
}

const cardKey = (word, sense) => `${word}${sense ? `#${sense}` : ''}`;

// -> the card's text at an indent: the house style, one field per line.
function cardText(card, indent) {
  const inner = indent + '  ';
  const lines = [`${indent}{`, `${inner}word: ${JSON.stringify(card.word)},`];
  if (card.sense) lines.push(`${inner}sense: ${JSON.stringify(card.sense)},`);
  if (card.hanzi) lines.push(`${inner}hanzi: ${JSON.stringify(card.hanzi)},`);
  lines.push(`${inner}en: ${JSON.stringify(card.en)},`, `${inner}ru: ${JSON.stringify(card.ru)},`, `${indent}},`);
  return lines.join('\n');
}

// -> the span of a card object's lines: its whole lines, trailing comma included.
function cardLines(src, obj) {
  const start = src.lastIndexOf('\n', obj.start) + 1;
  let end = obj.end;
  if (src[end] === ',') end++;
  if (src[end] === '\n') end++;
  return { start, end, indent: src.slice(start, obj.start) };
}

// -> a card object's fields as data.
function cardData(src, obj) {
  return Function(`return (${src.slice(obj.start, obj.end)});`)();
}

// Replaces one card (by `at`) with a list of cards (data), in place.
function spliceCards(ws, at, list) {
  const src = ws.get(at.file);
  const { start, end, indent } = cardLines(src, at.obj);
  const text = list.map((c) => cardText(c, indent) + '\n').join('');
  ws.set(at.file, src.slice(0, start) + text + src.slice(end));
}

function removeCard(ws, at) {
  spliceCards(ws, at, []);
  const src = ws.get(at.file);
  if (/words:\s*\[\s*\],?/.test(src)) {
    ws.set(at.file, src.replace(/\n\s*words:\s*\[\s*\],?/, ''));
  }
}

// Adds a card at the end of a module's words (creating the list if needed).
function appendCard(ws, file, card) {
  const src = ws.get(file);
  const m = src.match(/\n(\s*)words:\s*\[/);
  if (m) {
    const { objects } = scanSource(src);
    const listStart = m.index + m[0].length - 1;
    // the array's closing bracket: the first ']' after the last card object in it
    const inList = objects.filter((o) => o.key === 'words' && o.start > listStart);
    let close = src.indexOf(']', inList.length ? inList[inList.length - 1].end : listStart);
    const lineStart = src.lastIndexOf('\n', close) + 1;
    const indent = m[1] + '  ';
    ws.set(file, src.slice(0, lineStart) + cardText(card, indent) + '\n' + src.slice(lineStart));
    return;
  }
  const idLine = src.match(/\n(\s*)id: "[^"]+",\n/);
  if (!idLine) throw new Error(`${file}: no place for a words list`);
  const at = idLine.index + idLine[0].length;
  const indent = idLine[1];
  ws.set(file, src.slice(0, at) + `${indent}words: [\n${cardText(card, indent + '  ')}\n${indent}],\n` + src.slice(at));
}

// -> "lesson/module" -> the module's file.
export function moduleFile(ws, spec) {
  const [lesson, module] = spec.split('/');
  for (const file of moduleFiles(ws, lesson)) {
    if (ws.get(file).match(/lessonModule\(\{\s*id:\s*"([^"]+)"/)?.[1] === module) return file;
  }
  throw new Error(`no module "${spec}" (lesson/module ids, e.g. moving/far)`);
}

// -- glosses -------------------------------------------------------------------

// -> a short gloss from a definition: its first sense, refs written as terms.
function firstSense(ws, text) {
  const plain = text.replace(wordRefRe(), (full, kind, id) => (ws.hasWord(id) ? ws.word(id).term : id));
  return plain.split(/[;(]/)[0].split(',').slice(0, 2).join(',').trim();
}

function newCard(ws, id, sense) {
  const w = ws.word(id);
  if (sense) {
    const s = w.senses?.[sense];
    if (!s) throw new Error(`${id} has no sense "${sense}"`);
    return { word: id, sense, en: s.eng, ru: s.rus };
  }
  return { word: id, en: firstSense(ws, w.definition.eng), ru: firstSense(ws, w.definition.rus) };
}

// -- maps and coverage -------------------------------------------------------------

const MAPS = 'src/data/maps/';
const COVERAGE = 'src/data/coverage/';

function walkCategories(cats, fn) {
  for (const c of cats) {
    fn(c);
    walkCategories(c.children ?? [], fn);
  }
}

function categoryOf(ws, id) {
  let leaf = null;
  walkCategories(ws.data(`${MAPS}categories.ts`), (c) => {
    if ((c.wordIds ?? []).includes(id)) leaf = c.key;
  });
  return leaf;
}

// Rewrites every leaf's word list with fn(ids) -> ids.
function editCategories(ws, fn) {
  const cats = ws.data(`${MAPS}categories.ts`);
  walkCategories(cats, (c) => {
    if (c.wordIds) c.wordIds = fn(c.wordIds, c);
  });
  ws.setData(`${MAPS}categories.ts`, cats);
}

// Rewrites the antonym and synonym maps: pairs by pairFn([a, b]) -> pair | null,
// phrases by phraseFn(id, forms) -> [id, forms] | null; refs are rewritten later.
function editRelations(ws, pairFn, phraseFn, why) {
  for (const name of ['antonyms', 'synonyms']) {
    const path = `${MAPS}${name}.ts`;
    const r = ws.data(path);
    const pairs = [];
    for (const p of r.pairs) {
      const np = pairFn(p);
      if (np) pairs.push(np);
      else ws.note('relation', `${name}: dropped [${p.join(', ')}] (${why}) -- re-add by hand if it still holds`);
    }
    const phrases = {};
    for (const [id, forms] of Object.entries(r.phrases)) {
      const np = phraseFn(id, forms);
      if (np) phrases[np[0]] = np[1];
      else ws.note('relation', `${name}: dropped the phrase for ${id} (${why})`);
    }
    ws.setData(path, { pairs, phrases });
  }
}

function coverageFiles(ws) {
  return ws.files(COVERAGE).filter((r) => !r.endsWith('/index.ts') && !r.endsWith('/about.ts'));
}

function editCoverageWords(ws, fn) {
  for (const path of coverageFiles(ws)) {
    const g = ws.data(path);
    let touched = false;
    for (const item of g.items) {
      const nw = fn(item.words, item);
      if (nw !== item.words) {
        item.words = [...new Set(nw)];
        touched = true;
      }
    }
    if (touched) ws.setData(path, g);
  }
}

// -- rewriting references everywhere ----------------------------------------------

const isCode = (r) => /\.(ts|js|jsx)$/.test(r);

// Rewrites every ref to `id` in every file with make(kind). hanziFn, when
// given, rewrites the hanzi of each sentence that changed; every changed
// sentence is noted when noteSentences is set.
function rewriteAll(ws, id, make, opts = {}) {
  rewriteText(ws, (t) => replaceRefsTo(t, id, make), { ...opts, has: (t) => t.includes(`:${id}}}`) });
}

// Rewrites text everywhere with fn(text) -> text: string literals in code,
// whole files elsewhere, composite forms with their hanzi kept in step.
function rewriteText(ws, fn, { hanziFn, noteSentences = false, label, has = () => true } = {}) {
  const apply = (v) => fn(v);
  for (const path of ws.files()) {
    let src = ws.get(path);
    if (!has(src)) continue;
    if (path.startsWith(WORDS_DIR) || path.startsWith(COMPOSITES_DIR) || path.startsWith(MAPS) || path.startsWith(COVERAGE)) {
      // data: refs are inside string values; composites keep hsd/tts in step
      const r = rewriteStrings(src, (v) => apply(v));
      if (path.startsWith(COMPOSITES_DIR) && hanziFn) {
        const e = ws.data(path);
        const before = splitData(src, path).value;
        ws.set(path, r.text);
        const after = ws.data(path);
        (after.hsd ?? []).forEach((f, i) => {
          if (f !== before.hsd[i] && after.tts?.[i] != null) after.tts[i] = hanziFn(after.tts[i]);
        });
        ws.setComposite(path, after);
        void e;
      } else ws.set(path, r.text);
      continue;
    }
    if (isCode(path)) {
      const r = rewriteStrings(src, (v) => apply(v), hanziFn);
      ws.set(path, r.text);
      if (noteSentences) {
        for (const c of r.changed) {
          if (!SENTENCE_KEYS.has(c.key)) continue;
          const h = c.hanzi ? `  [${c.hanzi.before} -> ${c.hanzi.after}]` : '';
          ws.note('sentence', `${path}: ${label}: ${c.after}${h} -- check its en/ru`);
        }
      }
    } else {
      ws.set(path, apply(src));
      if (noteSentences && /\.yaml$/.test(path)) ws.note('sentence', `${path}: ${label}: YAML text changed -- check hanzi there by hand`);
    }
  }
}

// Rewrites plain-pinyin mentions of `term` (outside refs, and not a
// composite's own Mandarin pinyin) to `to`, capitalized where they were.
function rewriteMentions(ws, id, term, to) {
  const esc = term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`(^|[^\\p{L}])(${esc})(?![\\p{L}])`, 'giu');
  const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
  for (const path of ws.files()) {
    if (path === ws.wordPath(id)) continue;
    const src = ws.get(path);
    if (!src.toLowerCase().includes(term.toLowerCase())) continue;
    let n = 0;
    const out = src
      .split('\n')
      .map((line) => {
        if (path.startsWith(COMPOSITES_DIR) && /^\s*py:/.test(line)) return line;
        // leave refs alone: rewrite only the text between them
        return line
          .split(/(\{\{[^}]*\}\})/)
          .map((piece, k) => (k % 2 ? piece : piece.replace(re, (m, pre, word) => (n++, pre + (word[0] === word[0].toUpperCase() ? cap(to) : to)))))
          .join('');
      })
      .join('\n');
    if (n) {
      ws.set(path, out);
      ws.note('mention', `${path}: rewrote ${n} plain "${term}" as "${to}"`);
    }
  }
}

// Notes plain-text mentions of a word's term outside refs, and id strings in code.
function noteMentions(ws, id, term, why) {
  const forms = [...new Set([term, toneless(term)])].filter((f) => f.length > 2);
  for (const path of ws.files()) {
    if (path === ws.wordPath(id)) continue;
    const src = ws.get(path);
    const lines = src.split('\n');
    lines.forEach((line, i) => {
      if (path.startsWith(COMPOSITES_DIR) && /^\s*py:/.test(line)) return; // Mandarin's own pinyin
      const plain = line.replace(wordRefRe(), ' ');
      for (const f of forms) {
        const re = new RegExp(`(^|[^\\p{L}])${f.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\p{L}])`, 'iu');
        if (re.test(plain)) {
          ws.note('mention', `${path}:${i + 1}: "${f}" in plain text (${why})`);
          break;
        }
      }
      if (isCode(path) && !path.startsWith('src/data/') && new RegExp(`["']${id}["']`).test(line) && !/word:\s*"/.test(line))
        ws.note('code', `${path}:${i + 1}: the id "${id}" as a string in code (${why})`);
    });
  }
}

// -- pinyin --------------------------------------------------------------------

const TONE_MARKS = { a: 'āáǎà', e: 'ēéěè', i: 'īíǐì', o: 'ōóǒò', u: 'ūúǔù', ü: 'ǖǘǚǜ' };

// -> the syllables of an id: "dong1xi" -> ["dong1", "xi"], "de" -> ["de"].
export const idSyllables = (id) => id.match(/[a-z]+[1-5]|[a-z]+$/g) ?? [id];

// -> "dong1" -> "dōng", "nv3" -> "nǚ", "shi2jian1" -> "shíjiān", "de" -> "de".
export function idToTerm(id) {
  return idSyllables(id)
    .map((syl) => {
      const tone = /[1-5]$/.test(syl) ? Number(syl.slice(-1)) : 5;
      const s = syl.replace(/[1-5]$/, '').replace(/v/g, 'ü');
      if (tone === 5) return s;
      let at = s.search(/[ae]/);
      if (at < 0) at = s.indexOf('ou');
      if (at < 0) for (let k = 0; k < s.length; k++) if ('iouü'.includes(s[k])) at = k;
      if (at < 0) return s;
      return s.slice(0, at) + TONE_MARKS[s[at]][tone - 1] + s.slice(at + 1);
    })
    .join('');
}

