// The engine behind `npm run word` and `npm run refactor`: word refactors
// (add, split, replace, rename, move a card, ...) applied to an in-memory
// copy of the content, so a whole list of them can be shown as a dry run
// before anything is written.
//
// What it edits, and how:
//   - Data files (src/data/words, composites, maps, coverage) are loaded as
//     objects and written back with the same writer that formats them, so a
//     change is a small diff.
//   - Everything else under src/ (lesson modules, stories, the phrase book,
//     YAML and Markdown chapters, tests) is text. In JS/TS files only string
//     literals are rewritten (comments are left alone), and a sentence's
//     `hanzi`/`ttsText` follows its `pinyin`/`answer` when an op gives a
//     hanzi change. A vocabulary card is an object with `word: "<id>"`.
//   - What it can't decide is collected as notes for a hand edit: changed
//     sentences whose English/Russian may need a look, plain-text mentions
//     of a removed word, dropped relations, id strings in code.

