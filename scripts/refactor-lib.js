// -> per-file line counts of a change.
function lineDelta(before, after) {
  const a = (before ?? '').split('\n');
  const b = (after ?? '').split('\n');
  const setA = new Map();
  for (const l of a) setA.set(l, (setA.get(l) ?? 0) + 1);
  let common = 0;
  for (const l of b) if (setA.get(l)) setA.set(l, setA.get(l) - 1), common++;
  if (before == null) return { removed: 0, added: b.length };
  if (after == null) return { removed: a.length, added: 0 };
  return { removed: a.length - common, added: b.length - common };
}

export function summary(ws, { diff = false } = {}) {
  const out = [];
  const ch = ws.changes();
  for (const { path, before, after } of ch) {
    const tag = before == null ? 'new    ' : after == null ? 'deleted' : 'changed';
    const { added, removed } = lineDelta(before, after);
    out.push(`  ${tag}  ${path}  (+${added} -${removed})`);
    if (diff && before != null && after != null) {
      const a = before.split('\n');
      const b = after.split('\n');
      const bs = new Set(b);
      const as = new Set(a);
      for (const l of a) if (!bs.has(l)) out.push(`      - ${l.trim()}`);
      for (const l of b) if (!as.has(l)) out.push(`      + ${l.trim()}`);
    }
  }
  out.push(`\n${ch.length} file(s).`);
  const byKind = new Map();
  for (const n of ws.notes) byKind.set(n.kind, [...(byKind.get(n.kind) ?? []), n.text]);
  const TITLES = {
    todo: 'To do',
    card: 'Cards',
    sentence: 'Changed sentences (check their en/ru)',
    relation: 'Relations',
    composite: 'Composites',
    mention: 'Plain-text mentions (edit by hand)',
    code: 'Ids in code (check by hand)',
  };
  for (const [kind, list] of byKind) {
    out.push(`\n${TITLES[kind] ?? kind}:`);
    for (const t of [...new Set(list)]) out.push(`  - ${t}`);
  }
  return out.join('\n');
}
