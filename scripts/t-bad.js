#!/usr/bin/env node
// T-bad (BROWSER_TRANSLATOR_PLAN.md §3): bad English through step 0, in Claude sessions (scripts/tree-setup.js). The
// cases and the judge are in src/lib/translator/t-bad.js.
//
//   node scripts/t-bad.js              every case, 4 at a time -> kb/reports/t-bad.md
//   --only ID,ID  --jobs N  --model M (default sonnet)  --effort E  --claude PATH
//
// Exit 1 when a case fails.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { openTreeTranslator, mapJobs, loginMessage, ROOT } from './tree-setup.js';
import { CASES, judge, tally } from '../src/lib/translator/t-bad.js';

const { values } = parseArgs({
  options: { only: { type: 'string' }, jobs: { type: 'string', default: '4' }, model: { type: 'string', default: 'sonnet' }, effort: { type: 'string' }, claude: { type: 'string' } },
});
const only = values.only ? new Set(values.only.split(',')) : null;
const cases = CASES.filter((c) => !only || only.has(c.id));

const setup = await openTreeTranslator({ model: values.model, effort: values.effort, claude: values.claude });
const started = Date.now();
let results;
try {
  results = await mapJobs(cases, Number.parseInt(values.jobs, 10) || 4, async (kase) => {
    const correction = await setup.translator().correct(kase.text);
    const r = { ...kase, correction, ...judge(kase, correction) };
    console.error(`${r.pass ? 'pass' : 'FAIL'} ${kase.id}: ${r.outcome}${r.why.length ? ` (${r.why.join('; ')})` : ''}`);
    return r;
  });
} catch (e) {
  console.error(e.login ? loginMessage(setup.token) : (e.userMessage ?? e.stack ?? String(e)));
  process.exit(1);
}

const t = tally(results);
const seconds = Math.round((Date.now() - started) / 1000);
const quote = (s) => `"${String(s).replace(/\n/g, ' ')}"`;
const lines = [
  '# T-bad: bad English through step 0',
  '',
  `Generated by \`node scripts/t-bad.js\` (BROWSER_TRANSLATOR_PLAN.md §3), ${new Date().toISOString().slice(0, 10)}, model ${values.model}. Each case must be corrected (with the change shown), asked about or refused, never translated as it is; a control must pass with no question and no change of meaning. The cases are in \`src/lib/translator/t-bad.js\`.`,
  '',
  `- Cases: ${t.cases}; passed: ${t.passed}`,
  `- Corrected: ${t.corrected}; asked: ${t.asked}; refused: ${t.refused}; left as they were: ${t.same}`,
  `- Questions on a clean control: ${t.falseAsks}`,
  `- ${seconds} s, $${setup.cost()}`,
  '',
  '## Cases',
  '',
  ...results.flatMap((r) => [
    `- **${r.pass ? 'pass' : 'FAIL'}** ${r.id} (${r.kind}): ${quote(r.text)} → ${r.outcome}${r.why.length ? `: ${r.why.join('; ')}` : ''}`,
    ...(r.correction.sentences?.length && r.outcome !== 'refused' ? [`  - English: ${r.correction.sentences.map(quote).join(' ')}`] : []),
    ...(r.correction.changes ?? []).map((c) => `  - changed ${quote(c.from)} → ${quote(c.to)}${c.meaning ? ' (meaning)' : ''}: ${c.why}`),
    ...(r.outcome === 'ask' ? r.correction.questions.map((q) => `  - asks: ${q.about}${q.options?.length ? ` [${q.options.join(' / ')}]` : ''}`) : []),
    ...(r.outcome === 'refused' ? [`  - reason: ${r.correction.reason}`] : []),
  ]),
  '',
];
writeFileSync(join(ROOT, 'kb/reports/t-bad.md'), lines.join('\n'));
console.log(`T-bad: ${t.passed} of ${t.cases} pass; corrected ${t.corrected}, asked ${t.asked}, refused ${t.refused}, left ${t.same}; ${t.falseAsks} questions on controls; ${seconds} s, $${setup.cost()} -> kb/reports/t-bad.md`);
process.exit(t.passed === t.cases ? 0 : 1);
